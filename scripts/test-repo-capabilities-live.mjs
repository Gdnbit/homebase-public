import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {dispatch} from './repo-capabilities.mjs';
import {digest} from './repo-capabilities-store.mjs';

const lab=process.env.HOMEBASE_REPO_LAB;
assert(lab&&path.isAbsolute(lab),'Set an explicit isolated HOMEBASE_REPO_LAB');
const root=path.join(lab,`live-${crypto.randomUUID()}`);
fs.mkdirSync(root,{recursive:true});
const executable=fileURLToPath(new URL('../agent-runtime/tools/bwrap',import.meta.url));
const context={data_root:path.join(root,'registry'),output_root:path.join(root,'output'),sandbox:{kind:'wsl-bubblewrap',executable,sha256:digest(fs.readFileSync(executable)),distro:'Ubuntu'}};
const call=(action,input)=>dispatch(action,context,input);
const analyzed=await call('analyze',{repository_url:'https://github.com/markedjs/marked',request_id:'live-analyze'});
assert.equal(analyzed.project.phase,'analyzed',JSON.stringify(analyzed.project.error));
console.log('analyzed',analyzed.project.source.package.version);
const installed=await call('install',{project_id:analyzed.project.id,revision:analyzed.project.revision,request_id:'live-install'});
assert.equal(installed.project.phase,'registered',JSON.stringify(installed.project.error));
const capability_id=installed.project.capability_id;
console.log('registered',capability_id);
const input={stdin:'# HomeBase isolated verification\n\n**No provider key required.**\n'};
const first=await call('run',{capability_id,input,request_id:'live-run'});
assert.equal(first.status,'succeeded',JSON.stringify(first));
assert.match(first.stdout,/<h1>HomeBase isolated verification<\/h1>/);
assert.match(first.stdout,/<strong>No provider key required\.<\/strong>/);
const replay=await call('run',{capability_id,input,request_id:'live-run'});
assert.equal(replay.run_id,first.run_id);
assert.equal(replay.artifact.sha256,first.artifact.sha256);
await assert.rejects(call('run',{capability_id,input:{stdin:'changed'},request_id:'live-run'}),{code:'REQUEST_CONFLICT'});
await assert.rejects(call('run',{capability_id,input:{stdin:123},request_id:'invalid-run'}),{code:'CAPABILITY_INPUT_INVALID'});
const result=await call('result',{run_id:first.run_id});assert.equal(result.status,'succeeded');
const description=await call('describe',{capability_id});assert.equal(description.verification.passed,true);
assert.equal((await call('capabilities',{})).total,1);
assert.equal((await call('projects',{})).total,1);
const long=await call('run',{capability_id,input:{stdin:'a'.repeat(40000)},request_id:'long-output'});assert.equal(long.status,'succeeded');assert.equal(long.stdout_truncated,true);assert(fs.readFileSync(long.artifact.path,'utf8').includes('a'.repeat(40000)));
fs.writeFileSync(path.join(root,'report.json'),JSON.stringify({passed:true,context,project_id:installed.project.id,capability_id,run_id:first.run_id,artifact:first.artifact,checks:['public-source-pinning','ignore-scripts-install','namespace-cli-help-version','golden-behavior','schema-rejection','replay-no-duplicate','request-conflict','query-result']},null,2));
console.log(JSON.stringify({passed:true,root,capability_id,run_id:first.run_id}));
